-- Baseline schema for the synthetic order dataset and order lookup app.
create table if not exists customers (
    id bigint generated by default as identity primary key,
    full_name text not null,
    email text not null unique check (email = lower(email)),
    phone text not null check (phone ~ '^[0-9]{10}$'),
    created_at timestamptz not null default now()
);
create index if not exists customers_phone_idx on customers(phone);

create table if not exists customer_addresses (
    id bigint generated by default as identity primary key,
    customer_id bigint not null references customers(id) on delete cascade,
    label text not null default 'Home',
    line1 text not null,
    city text not null,
    state_or_region text not null,
    postal_code text not null,
    country_code char(2) not null,
    is_default boolean not null default false
);
create index if not exists customer_addresses_customer_idx on customer_addresses(customer_id);

create table if not exists orders (
    public_order_id integer generated by default as identity
        (start with 1 minvalue 1 maxvalue 1000) primary key,
    customer_id bigint not null references customers(id),
    status text not null check (status in (
        'Processing', 'In Transit', 'Out for Delivery', 'Delivered', 'Cancelled', 'Failed Delivery'
    )),
    priority text not null default 'Standard',
    payment_status text not null check (payment_status in ('Pending', 'Paid', 'Failed', 'Refunded')),
    currency char(3) not null,
    subtotal numeric(12, 2) not null check (subtotal >= 0),
    shipping_fee numeric(12, 2) not null default 0 check (shipping_fee >= 0),
    tax_amount numeric(12, 2) not null default 0 check (tax_amount >= 0),
    total_amount numeric(12, 2) generated always as (subtotal + shipping_fee + tax_amount) stored,
    special_instructions text,
    ordered_at timestamptz not null default now(),
    cancelled_at timestamptz
);
create index if not exists orders_customer_ordered_idx on orders(customer_id, ordered_at desc);

create table if not exists order_delivery_addresses (
    order_id integer primary key references orders(public_order_id) on delete cascade,
    recipient_name text not null,
    line1 text not null,
    city text not null,
    state_or_region text not null,
    postal_code text not null,
    country_code char(2) not null
);

create table if not exists order_items (
    id bigint generated by default as identity primary key,
    order_id integer not null references orders(public_order_id) on delete cascade,
    product_sku text not null,
    product_name text not null,
    quantity integer not null check (quantity > 0),
    unit_price numeric(12, 2) not null check (unit_price >= 0)
);
create index if not exists order_items_order_idx on order_items(order_id);

-- The application currently presents one shipment per order; enforce that
-- assumption here. Model parcels separately before changing this constraint.
create table if not exists shipments (
    order_id integer primary key references orders(public_order_id) on delete cascade,
    carrier text not null,
    tracking_number text not null unique,
    delivery_driver_name text,
    estimated_delivery_at timestamptz,
    delivered_at timestamptz,
    delivery_time_slot text
);

create table if not exists order_events (
    id bigint generated by default as identity primary key,
    order_id integer not null references orders(public_order_id) on delete cascade,
    event_type text not null,
    event_at timestamptz not null,
    message text
);
create index if not exists order_events_order_time_idx on order_events(order_id, event_at desc);

create table if not exists payments (
    id bigint generated by default as identity primary key,
    order_id integer not null references orders(public_order_id) on delete cascade,
    provider text not null,
    provider_payment_id text not null unique,
    amount numeric(12, 2) not null check (amount >= 0),
    currency char(3) not null,
    status text not null,
    paid_at timestamptz
);
create index if not exists payments_order_idx on payments(order_id);

create or replace function sync_order_number_sequence()
returns void
language plpgsql
as $$
declare
    v_max integer;
begin
    select max(public_order_id) into v_max from orders;
    perform setval(
        pg_get_serial_sequence('public.orders', 'public_order_id'),
        coalesce(v_max, 1),
        v_max is not null
    );
end;
$$;

create or replace function sync_simple_id_sequences()
returns void
language plpgsql
as $$
declare
    v_column record;
    v_max bigint;
    v_sequence text;
begin
    for v_column in
        select table_name, column_name
        from information_schema.columns
        where table_schema = 'public'
          and is_identity = 'YES'
          and table_name <> 'orders'
    loop
        execute format('select max(%I) from public.%I', v_column.column_name, v_column.table_name)
            into v_max;
        v_sequence := pg_get_serial_sequence(
            format('public.%I', v_column.table_name), v_column.column_name
        );
        perform setval(v_sequence, coalesce(v_max, 1), v_max is not null);
    end loop;
end;
$$;

