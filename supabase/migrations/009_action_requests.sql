-- Customer-approved requests for human review. These rows do not trigger an
-- order cancellation or return; an operator must review and execute the action.
create table if not exists action_requests (
    id bigint generated by default as identity primary key,
    request_key uuid not null unique,
    action_type text not null check (action_type in ('return_request', 'cancel_request')),
    order_id integer not null references orders(public_order_id) on delete cascade,
    reason text not null default 'Customer request' check (char_length(reason) <= 300),
    conversation_id uuid references conversations(id) on delete set null,
    status text not null check (status in ('submitted', 'completed', 'rejected', 'failed')),
    confirmed_at timestamptz not null,
    created_at timestamptz not null default now()
);

create index if not exists action_requests_order_time_idx
    on action_requests(order_id, created_at desc);

alter table action_requests enable row level security;
