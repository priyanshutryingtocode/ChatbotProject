-- Keep resumable conversation structure while removing stored order/identity
-- content and fields that the application never reads.

update messages
set content = '[Historical message redacted]';

alter table messages drop column if exists db_results;
alter table conversations drop column if exists customer_email;

alter table messages
    add column if not exists message_seq bigint generated by default as identity;

drop index if exists messages_conversation_created_idx;
create index if not exists messages_conversation_sequence_idx
    on messages (conversation_id, message_seq desc);

create or replace function touch_conversation_updated_at()
returns trigger
language plpgsql
as $$
begin
    update conversations set updated_at = now() where id = new.conversation_id;
    return new;
end;
$$;

drop trigger if exists messages_touch_conversation on messages;
create trigger messages_touch_conversation
after insert on messages
for each row execute function touch_conversation_updated_at();
